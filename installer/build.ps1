<#
    Build the JARVIS installer.

        powershell -ExecutionPolicy Bypass -File installer\build.ps1

    Requires Inno Setup 6 (ISCC.exe) and git.
    Produces dist\JARVIS-Setup-<version>.exe

    The shipped file list is generated here from `git ls-files`, so the
    installer can only ever contain tracked files. That is the safety
    story: .env, logs/, voices/*.onnx, memory/*.db and docs/research/
    are all gitignored and therefore unshippable. On top of that, the
    list is checked against the sensitive-path list below and the build
    refuses to continue if anything looks like a secret - a leak is the
    one mistake here that cannot be undone by a later commit.
#>
[CmdletBinding()]
param(
    [string]$Iscc
)

$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
$installerDir = $PSScriptRoot
Set-Location $root

# -- version: config.py is the single source of truth -----------------
$configText = Get-Content -LiteralPath (Join-Path $root 'config.py') -Raw
if ($configText -notmatch 'VERSION\s*=\s*"([^"]+)"') {
    throw 'could not read VERSION from config.py'
}
$version = $Matches[1]
Write-Host "JARVIS version  : $version" -ForegroundColor Cyan

# -- shipped file list: tracked files only ----------------------------
if (-not (Get-Command git -ErrorAction SilentlyContinue)) {
    throw 'git is required: the file list is generated from `git ls-files`.'
}
$tracked = & git ls-files
if (-not $tracked) {
    throw '`git ls-files` returned nothing - run this from inside the repository.'
}

# Repo plumbing that means nothing inside an install, and the
# installer's own files (shipped explicitly, see jarvis.iss).
$files = @($tracked | Where-Object { $_ -notmatch '^(\.github|\.vscode|installer)/' })

# -- refuse to package anything that smells like a secret -------------
$mustShip = @('config.py', '.env.example', 'run.py', 'desktop.py',
              'static/js/app.js', 'templates/index.html', 'requirements.txt')
foreach ($needed in $mustShip) {
    if ($files -notcontains $needed) {
        throw "expected '$needed' to ship, but it is not in the tracked file list"
    }
}
$sensitive = $files | Where-Object {
    $_ -ne '.env.example' -and ($_ -match '^\.env($|\.)' -or
    $_ -match '(?i)\.(db|db-wal|db-shm|onnx|wav|bak|appinstaller)$' -or
    $_ -match '^logs/' -or $_ -match '^docs/research/' -or
    $_ -match '^(mcp_servers\.json|jarvis_config\.json|https\.txt|\.agent-state\.md)$')
}
if ($sensitive) {
    throw ("refusing to build - these sensitive paths are in the shipped list: " +
           ($sensitive -join ', '))
}

$lines = New-Object System.Collections.Generic.List[string]
$lines.Add('; GENERATED by installer\build.ps1 from `git ls-files` - do not edit.')
$lines.Add("; JARVIS $version - $($files.Count) files")
$lines.Add('')
foreach ($relative in $files) {
    $source = '..\' + ($relative -replace '/', '\')
    $dir = Split-Path -Parent $relative
    $dest = if ($dir) { '{app}\' + ($dir -replace '/', '\') } else { '{app}' }
    $lines.Add(('Source: "{0}"; DestDir: "{1}"; Flags: ignoreversion' -f $source, $dest))
}
Set-Content -LiteralPath (Join-Path $installerDir 'files.iss') -Value $lines -Encoding UTF8
Write-Host "shipped files   : $($files.Count) (tracked, minus .github/.vscode/installer)" -ForegroundColor Cyan

# -- compiler ---------------------------------------------------------
if (-not $Iscc) {
    $Iscc = @(
        (Join-Path $env:LOCALAPPDATA 'Programs\Inno Setup 6\ISCC.exe'),
        'C:\Program Files (x86)\Inno Setup 6\ISCC.exe',
        'C:\Program Files\Inno Setup 6\ISCC.exe'
    ) | Where-Object { Test-Path -LiteralPath $_ } | Select-Object -First 1
}
if (-not $Iscc -or -not (Test-Path -LiteralPath $Iscc)) {
    throw 'Inno Setup 6 not found. Install it with `winget install JRSoftware.InnoSetup`, or pass -Iscc <path>.'
}
Write-Host "compiler        : $Iscc" -ForegroundColor Cyan

$distDir = Join-Path $root 'dist'
New-Item -ItemType Directory -Force -Path $distDir | Out-Null

& $Iscc "/DMyAppVersion=$version" (Join-Path $installerDir 'jarvis.iss')
if ($LASTEXITCODE -ne 0) {
    throw "Inno Setup failed with exit code $LASTEXITCODE"
}

$artifact = Join-Path $distDir "JARVIS-Setup-$version.exe"
if (-not (Test-Path -LiteralPath $artifact)) {
    throw "the build reported success but produced no artifact at $artifact"
}

$sizeMb = [math]::Round((Get-Item -LiteralPath $artifact).Length / 1MB, 1)
Write-Host ''
Write-Host "  [ok] $artifact" -ForegroundColor Green
Write-Host "       $sizeMb MB, version $version" -ForegroundColor Gray
Write-Host ''
